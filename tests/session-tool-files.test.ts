import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { registerCreatedToolFiles } from '../lib/session-tool-files.js';
import { listSessionFiles } from '../lib/session-files.js';
import { sendBridgeMediaItem } from '../lib/bridge/bridge-attachments.js';
let cwd: string, session: string;
beforeEach(() => {
  cwd = fs.mkdtempSync(path.join(os.tmpdir(), 'lynn-tool-files-'));
  session = path.join(cwd, 'session.jsonl');
  fs.writeFileSync(session, '{}\n');
  fs.writeFileSync(path.join(cwd, 'report.md'), 'generated report');
});
afterEach(() => fs.rmSync(cwd, { recursive: true, force: true }));
describe('tool-created attachments without a GUI', () => {
  it('registers successful native writes and structured generated documents', () => {
    registerCreatedToolFiles(session, 'write', { path: 'report.md' }, {}, cwd);
    registerCreatedToolFiles(session, 'create_docx', {}, { details: { files: [{ filePath: path.join(cwd, 'report.md') }] } }, cwd);
    expect(listSessionFiles(session)).toHaveLength(1);
    expect(listSessionFiles(session)[0].name).toBe('report.md');
  });
  it('does not turn model text, arbitrary tool details, or failed writes into send permission', () => {
    const result = { content: [{ type: 'text', text: 'MEDIA:' + path.join(cwd, 'report.md') }], details: { filePath: path.join(cwd, 'report.md') } };
    registerCreatedToolFiles(session, 'web_fetch', {}, result, cwd);
    registerCreatedToolFiles(session, 'bash', {}, result, cwd);
    registerCreatedToolFiles(session, 'write', { path: 'report.md' }, { isError: true }, cwd);
    expect(listSessionFiles(session)).toEqual([]);
  });
  it('keeps missing files unavailable and tolerates an unpersisted session', () => {
    registerCreatedToolFiles(session, 'create_report', {}, { details: { files: [{ filePath: path.join(cwd, 'missing') }] } }, cwd);
    registerCreatedToolFiles(undefined, 'write', { path: 'report.md' }, {}, cwd);
    expect(listSessionFiles(session)).toEqual([]);
  });
  it('sends registered generated bytes after completion and rejects another session', async () => {
    const output = path.join(cwd, 'report.md');
    registerCreatedToolFiles(session, 'write', { path: output }, {}, cwd);
    const adapter = { sendMediaBuffer: vi.fn(async () => undefined) } as any;
    await sendBridgeMediaItem(adapter, 'chat', output, session);
    expect(adapter.sendMediaBuffer.mock.calls[0][1].toString()).toBe('generated report');
    const other = path.join(cwd, 'other.jsonl'); fs.writeFileSync(other, '{}\n');
    await expect(sendBridgeMediaItem(adapter, 'chat', output, other)).rejects.toThrow('registered');
  });

});
